#!/usr/bin/env python3
"""
Pod 5 — Digital Product Generator (PDF Guides, Planners, Templates).

Uses WeasyPrint + Jinja2 to convert content briefs into beautifully styled
PDF digital products for Gumroad, Etsy, and Whop.

Falls back to simple HTML→text PDF if WeasyPrint is not installed.

Usage:
    python scripts/digital_product_generator.py [--brief-id 1] [--type pdf_guide]
"""
